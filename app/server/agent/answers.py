def phrases_for(answer: ModelAnswer, situation: str) -> tuple[str, ...]:
    """説明が閉じているときに差し替える語句。保留では結果の言い回しも足す"""
    if situation == "hold":
        return answer.leak_phrases + answer.result_phrases
    return answer.leak_phrases


